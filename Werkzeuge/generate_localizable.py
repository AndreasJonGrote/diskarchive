def entry(key: str, de: str, en: str, comment: str | None) -> dict:
    item: dict = {
        "localizations": {
            "de": {"stringUnit": {"state": "translated", "value": de}},
            "en": {"stringUnit": {"state": "translated", "value": en}},
        }
    }
    if comment:
        item["comment"] = comment
    return item


def main() -> None:
    strings = {key: entry(key, de, en, comment) for key, de, en, comment in ENTRIES}
    catalog = {
        "sourceLanguage": "de",
        "strings": strings,
        "version": "1.0",
    }
    out = Path(__file__).resolve().parent.parent / "diskindex/diskindex/Localization/Localizable.xcstrings"
    out.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(strings)} keys to {out}")


if __name__ == "__main__":
    main()
